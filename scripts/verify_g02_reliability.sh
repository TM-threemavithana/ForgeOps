#!/usr/bin/env bash
# ForgeOps Gate G02 — Persistence, Restart, and Recovery Verification
# Validates PostgreSQL volume persistence across container recreation,
# API container restart recovery, and database restart connection pool recovery.

set -euo pipefail

BASE_URL="http://127.0.0.1:18080"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
EVIDENCE_DIR="$REPO_ROOT/docs/evidence/G02"
LOG="$EVIDENCE_DIR/persistence-and-recovery.log"

echo "=== ForgeOps Gate G02 Reliability & Persistence Verification ===" > "$LOG"
date -u +"Date (UTC): %Y-%m-%dT%H:%M:%SZ" >> "$LOG"
echo "" >> "$LOG"

# Source the test identity generated by the smoke test
# shellcheck source=/dev/null
source "$EVIDENCE_DIR/test_identity.env"

echo "Using Test Project ID: $PERSISTENCE_TEST_PROJ_ID" | tee -a "$LOG"
echo "Using Test Task ID: $PERSISTENCE_TEST_TASK_ID" | tee -a "$LOG"
echo "" | tee -a "$LOG"

# ------------------------------------------------------------------------------
# Part 1: Verify database state in PostgreSQL before container recreation
# ------------------------------------------------------------------------------
echo "--- Part 1: Inspecting PostgreSQL Records Before Stack Recreation ---" | tee -a "$LOG"
docker exec forgeops-postgres psql -U forgeuser -d forgetasks -c \
    "SELECT id, name, version FROM projects WHERE id = '$PERSISTENCE_TEST_PROJ_ID';" >> "$LOG" 2>&1
echo "[PASS] Project record verified in PostgreSQL container" | tee -a "$LOG"
echo "" >> "$LOG"

# ------------------------------------------------------------------------------
# Part 2: Controlled graceful shutdown (preserving named volume)
# ------------------------------------------------------------------------------
echo "--- Part 2: Graceful Stack Shutdown (docker compose down WITHOUT -v) ---" | tee -a "$LOG"
cd "$REPO_ROOT"
docker compose down >> "$LOG" 2>&1
echo "[PASS] Compose stack stopped gracefully" | tee -a "$LOG"

# Verify volume still exists on host
VOLUME_EXISTS=$(docker volume ls --filter name=forgeops-g02-postgres-data -q)
if [ -n "$VOLUME_EXISTS" ]; then
    echo "[PASS] Dedicated PostgreSQL volume '$VOLUME_EXISTS' preserved on host" | tee -a "$LOG"
else
    echo "[FAIL] Dedicated PostgreSQL volume was deleted!" | tee -a "$LOG"
    exit 1
fi
echo "" >> "$LOG"

# ------------------------------------------------------------------------------
# Part 3: Container Recreation & Persistence Verification
# ------------------------------------------------------------------------------
echo "--- Part 3: Recreating Stack Containers From Preserved Volume ---" | tee -a "$LOG"
docker compose up -d >> "$LOG" 2>&1

echo "Waiting for services to become healthy..." | tee -a "$LOG"
for i in {1..30}; do
    STATUS=$(docker inspect --format='{{.State.Health.Status}}' forgeops-api 2>/dev/null || echo "starting")
    if [ "$STATUS" = "healthy" ]; then
        echo "[PASS] forgeops-api transitioned to healthy after recreation (attempt $i)" | tee -a "$LOG"
        break
    fi
    sleep 2
done

# Query API to confirm data survived container recreation
RECREATED_PROJ_CODE=$(curl -s -o /tmp/rec_proj.json -w "%{http_code}" \
    -u "$PERSISTENCE_TEST_USER_A:$PERSISTENCE_TEST_PASS_A" \
    "$BASE_URL/api/v1/projects/$PERSISTENCE_TEST_PROJ_ID")

if [ "$RECREATED_PROJ_CODE" -eq 200 ]; then
    echo "[PASS] Verified data persistence: Project survived container recreation (HTTP 200)" | tee -a "$LOG"
    cat /tmp/rec_proj.json >> "$LOG"
    echo -e "\n" >> "$LOG"
else
    echo "[FAIL] Project data was lost during container recreation! (HTTP $RECREATED_PROJ_CODE)" | tee -a "$LOG"
    exit 1
fi

RECREATED_TASK_CODE=$(curl -s -o /tmp/rec_task.json -w "%{http_code}" \
    -u "$PERSISTENCE_TEST_USER_A:$PERSISTENCE_TEST_PASS_A" \
    "$BASE_URL/api/v1/tasks/$PERSISTENCE_TEST_TASK_ID")

if [ "$RECREATED_TASK_CODE" -eq 200 ]; then
    echo "[PASS] Verified data persistence: Task survived container recreation (HTTP 200)" | tee -a "$LOG"
    cat /tmp/rec_task.json >> "$LOG"
    echo -e "\n" >> "$LOG"
else
    echo "[FAIL] Task data was lost during container recreation! (HTTP $RECREATED_TASK_CODE)" | tee -a "$LOG"
    exit 1
fi

# ------------------------------------------------------------------------------
# Part 4: API-Only Container Restart Test
# ------------------------------------------------------------------------------
echo "--- Part 4: Restarting API Container Only ---" | tee -a "$LOG"
docker compose restart forgetasks-api >> "$LOG" 2>&1

echo "Waiting for API container to recover health..." | tee -a "$LOG"
for i in {1..30}; do
    STATUS=$(docker inspect --format='{{.State.Health.Status}}' forgeops-api 2>/dev/null || echo "starting")
    if [ "$STATUS" = "healthy" ]; then
        echo "[PASS] forgeops-api healthy after standalone restart (attempt $i)" | tee -a "$LOG"
        break
    fi
    sleep 2
done

POST_RESTART_CODE=$(curl -s -o /tmp/post_restart.json -w "%{http_code}" \
    -u "$PERSISTENCE_TEST_USER_A:$PERSISTENCE_TEST_PASS_A" \
    "$BASE_URL/api/v1/projects/$PERSISTENCE_TEST_PROJ_ID")
if [ "$POST_RESTART_CODE" -eq 200 ]; then
    echo "[PASS] API container restart test passed: project accessible after restart" | tee -a "$LOG"
else
    echo "[FAIL] API container restart failed: HTTP $POST_RESTART_CODE" | tee -a "$LOG"
    exit 1
fi
echo "" >> "$LOG"

# ------------------------------------------------------------------------------
# Part 5: Database Restart & Connection Pool Recovery Test
# ------------------------------------------------------------------------------
echo "--- Part 5: Controlled Database Restart & Connection Pool Recovery ---" | tee -a "$LOG"
docker compose restart postgres >> "$LOG" 2>&1

echo "Waiting for PostgreSQL to become healthy..." | tee -a "$LOG"
for i in {1..30}; do
    PG_STATUS=$(docker inspect --format='{{.State.Health.Status}}' forgeops-postgres 2>/dev/null || echo "starting")
    if [ "$PG_STATUS" = "healthy" ]; then
        echo "[PASS] PostgreSQL service recovered and reported healthy (attempt $i)" | tee -a "$LOG"
        break
    fi
    sleep 2
done

echo "Verifying API readiness recovery..." | tee -a "$LOG"
for i in {1..30}; do
    READY_STATUS=$(curl -s "$BASE_URL/actuator/health/readiness" | grep -o '"status":"[^"]*' | head -n 1 | cut -d'"' -f4 || echo "DOWN")
    if [ "$READY_STATUS" = "UP" ]; then
        echo "[PASS] API readiness recovered to UP following PostgreSQL restart (attempt $i)" | tee -a "$LOG"
        break
    fi
    sleep 2
done

POST_DB_RESTART_CODE=$(curl -s -o /tmp/post_db.json -w "%{http_code}" \
    -u "$PERSISTENCE_TEST_USER_A:$PERSISTENCE_TEST_PASS_A" \
    "$BASE_URL/api/v1/projects/$PERSISTENCE_TEST_PROJ_ID")
if [ "$POST_DB_RESTART_CODE" -eq 200 ]; then
    echo "[PASS] Database restart recovery passed: HikariCP reconnected and served request" | tee -a "$LOG"
else
    echo "[FAIL] Database restart recovery failed: HTTP $POST_DB_RESTART_CODE" | tee -a "$LOG"
    exit 1
fi

echo "" | tee -a "$LOG"
echo "=== Reliability & Recovery Summary ===" | tee -a "$LOG"
echo "All Persistence, API Restart, and Database Recovery tests passed cleanly." | tee -a "$LOG"

# Clean up temporary response files
rm -f /tmp/rec_proj.json /tmp/rec_task.json /tmp/post_restart.json /tmp/post_db.json
